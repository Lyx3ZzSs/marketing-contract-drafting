import { expect, it, vi } from 'vitest'
import { PdfPageCache } from './pdf-page-cache'

it('keeps recently read pages and evicts the oldest inactive bitmap over budget', () => {
  const cache = new PdfPageCache(100)
  const a = Symbol(), b = Symbol(), c = Symbol()
  const releaseA = vi.fn(), releaseB = vi.fn(), releaseC = vi.fn()
  cache.set(a, 40, false, releaseA)
  cache.set(b, 40, false, releaseB)
  cache.protect(a, true)
  cache.protect(a, false)
  cache.set(c, 40, true, releaseC)
  expect(releaseB).toHaveBeenCalledOnce()
  expect(releaseA).not.toHaveBeenCalled()
  expect(releaseC).not.toHaveBeenCalled()
  expect(cache.bytes).toBe(80)
})
it('protects nearby pages and trims once they leave the prefetch region', () => {
  const cache = new PdfPageCache(100)
  const a = Symbol(), b = Symbol()
  const releaseA = vi.fn(), releaseB = vi.fn()
  cache.set(a, 80, true, releaseA)
  cache.set(b, 80, true, releaseB)
  expect(cache.bytes).toBe(160)
  expect(releaseA).not.toHaveBeenCalled()
  cache.protect(a, false)
  expect(releaseA).toHaveBeenCalledOnce()
  expect(releaseB).not.toHaveBeenCalled()
  expect(cache.bytes).toBe(80)
})
it('releases replaced and unmounted frames exactly once', () => {
  const cache = new PdfPageCache(100)
  const key = Symbol(), releaseA = vi.fn(), releaseB = vi.fn()
  cache.set(key, 40, true, releaseA)
  cache.set(key, 60, true, releaseB)
  expect(releaseA).toHaveBeenCalledOnce()
  expect(cache.bytes).toBe(60)
  cache.delete(key)
  cache.delete(key)
  expect(cache.bytes).toBe(0)
  expect(releaseB).toHaveBeenCalledOnce()
})
